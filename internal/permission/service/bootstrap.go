package service

import (
	"github.com/google/uuid"
	"gorm.io/datatypes"

	"github.com/rouroumaibing/software-distribution-platform-hub/internal/permission/models"
)

// BuiltinPlatformAdminRoleName is the platform-admin role name. It matches the
// console's L1 route guard and the bootstrap admin's realm role, so userinfo
// can drive menu visibility without a name mapping. It is also the seed's
// idempotency key: the role is matched by name, not by a fixed UUID.
const BuiltinPlatformAdminRoleName = "platform-admin"

// BuiltinPlatformAdminActions is the full action set for the built-in admin.
// It mirrors 09_rbac_multiorg.sql so a code-seeded role and a SQL-seeded role
// grant exactly the same permissions.
const builtinPlatformAdminActionsJSON = `["page:overview:view","page:servicetree:view","page:settings:view","org:manage","user:manage","ops:manage","component:create","environment:create"]`

// builtinAdminGroup is the realm group the bootstrap admin belongs to. With the
// groups mapper's full.path=true the token claim is "/sdp-admin" verbatim.
const builtinAdminGroup = "/sdp-admin"

// bootstrapRoleStore and bootstrapBindingStore are the narrow persistence
// surfaces EnsureBuiltinPlatformRBAC needs. The concrete repositories satisfy
// them; stubs keep the idempotence logic unit-testable without Postgres.
type bootstrapRoleStore interface {
	GetByName(name string) (*models.PlatformRole, error)
	Create(item *models.PlatformRole) error
}

type bootstrapBindingStore interface {
	ExistsActive(orgID *uuid.UUID, subjectType, subjectID string, roleID uuid.UUID) (bool, error)
	Create(item *models.PlatformRoleBinding) error
}

// EnsureBuiltinPlatformRBAC seeds the built-in platform role and the bootstrap
// admin group binding at startup. It is idempotent: an existing role (matched
// by name) or binding (matched by subject + role) is left untouched, so a
// platform admin's changes to the built-in role are never overwritten.
//
// Neither row carries a hard-coded UUID. The role's ID is generated by the
// database and the binding points at whatever ID the role ended up with; the
// seed therefore stays consistent across fresh installs and against the
// pre-existing rows of an upgraded install without a data migration.
//
// This removes the dependency on manually importing conf SQL: a freshly
// rebuilt environment gets a working platform-admin grant on first boot.
func EnsureBuiltinPlatformRBAC(roles bootstrapRoleStore, bindings bootstrapBindingStore) error {
	role, err := roles.GetByName(BuiltinPlatformAdminRoleName)
	if err != nil || role == nil {
		role = &models.PlatformRole{
			Name:        BuiltinPlatformAdminRoleName,
			Description: "平台管理员：全部页面与全局动作",
			Actions:     datatypes.JSON(builtinPlatformAdminActionsJSON),
			IsSystem:    true,
		}
		if err := roles.Create(role); err != nil {
			// Another replica may have inserted it between our read and write.
			// Re-read by name; a hit means the role exists and is usable.
			if raced, rerr := roles.GetByName(BuiltinPlatformAdminRoleName); rerr == nil && raced != nil {
				role = raced
			} else {
				return err
			}
		}
	}

	exists, err := bindings.ExistsActive(nil, SubjectTypeGroup, builtinAdminGroup, role.ID)
	if err != nil {
		return err
	}
	if exists {
		return nil
	}
	binding := &models.PlatformRoleBinding{
		SubjectType:    SubjectTypeGroup,
		SubjectID:      builtinAdminGroup,
		PlatformRoleID: role.ID,
	}
	if err := bindings.Create(binding); err != nil {
		// Same read-then-write race as the role above. Re-check the natural
		// key; a hit means a replica inserted the grant meanwhile.
		if raced, rerr := bindings.ExistsActive(nil, SubjectTypeGroup, builtinAdminGroup, role.ID); rerr == nil && raced {
			return nil
		}
		return err
	}
	return nil
}
